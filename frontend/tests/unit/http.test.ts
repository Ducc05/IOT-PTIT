import { afterEach, expect, it, vi } from 'vitest'
import { createHttpApi } from '../../src/api/http'
import { auth } from '../../src/api/auth'
afterEach(() => { auth.logout(); vi.unstubAllGlobals() })
it('maps the interface to the backend wire URLs and command body', async () => {
  const fetch = vi.fn().mockResolvedValueOnce({ ok: true, status: 200, json: async () => ({ access: 'access-token', refresh: 'refresh-token' }) })
    .mockResolvedValueOnce({ ok: true, status: 200, json: async () => ({ id: 1, username: 'operator', email: '' }) })
    .mockResolvedValue({ ok: true, status: 200, json: async () => ({ count: 0, next: null, previous: null, results: [] }) })
  vi.stubGlobal('fetch', fetch)
  await auth.login('operator', 'test-only')
  const api = createHttpApi('http://localhost:8000/api/v1/')
  await api.sensorLatest()
  expect(fetch.mock.calls[2][0]).toBe('http://localhost:8000/api/v1/sensor-data/latest/')
  await api.sensorTrends()
  expect(fetch.mock.calls[3][0]).toBe('http://localhost:8000/api/v1/sensor-data/trends/?samples=20')
  await api.sensorData({ search: 'TEMP_01', from: '2026-10-06T12:00:00Z', page: 2, page_size: 15 })
  expect(fetch.mock.calls[4][0]).toBe('http://localhost:8000/api/v1/sensor-data/?search=TEMP_01&from=2026-10-06T12%3A00%3A00Z&limit=15&offset=15')
  expect(fetch.mock.calls[4][1].headers.Authorization).toBe('Bearer access-token')
  const body = { action: 'TURN_ON' as const, idempotency_key: 'same-key' }
  await api.control(1, body)
  expect(fetch.mock.calls[5][0]).toBe('http://localhost:8000/api/v1/devices/1/control/')
  expect(fetch.mock.calls[5][1]).toMatchObject({ method: 'POST', body: JSON.stringify(body), cache: 'no-store' })
  expect(fetch.mock.calls[5][1].headers.Authorization).toBe('Bearer access-token')
  await api.command('example-uuid')
  expect(fetch.mock.calls[6][0]).toBe('http://localhost:8000/api/v1/device-history/example-uuid/')
})
it('refreshes an expired access token and retries the same command intent', async () => {
  const fetch = vi.fn()
    .mockResolvedValueOnce({ ok: true, status: 200, json: async () => ({ access: 'old', refresh: 'refresh-token' }) })
    .mockResolvedValueOnce({ ok: true, status: 200, json: async () => ({ id: 1, username: 'operator', email: '' }) })
    .mockResolvedValueOnce({ ok: false, status: 401, json: async () => ({ error: { code: 'AUTHENTICATION_REQUIRED' } }) })
    .mockResolvedValueOnce({ ok: true, status: 200, json: async () => ({ access: 'new' }) })
    .mockResolvedValueOnce({ ok: true, status: 202, json: async () => ({ status: 'PENDING' }) })
  vi.stubGlobal('fetch', fetch)
  await auth.login('operator', 'test-only')
  const body = { action: 'TURN_ON' as const, idempotency_key: 'same-key' }
  await createHttpApi('http://localhost:8000/api/v1').control(1, body)
  expect(fetch.mock.calls[3][0]).toBe('http://localhost:8000/api/auth/token/refresh/')
  expect(fetch.mock.calls[2][1].body).toBe(fetch.mock.calls[4][1].body)
  expect(fetch.mock.calls[4][1].headers.Authorization).toBe('Bearer new')
})
it('updates the current profile with the refreshed JWT and keeps the saved fields', async () => {
  const fetch = vi.fn()
    .mockResolvedValueOnce({ ok: false, status: 401, json: async () => ({ detail: 'Expired.' }) })
    .mockResolvedValueOnce({ ok: true, status: 200, json: async () => ({ access: 'new-access' }) })
    .mockResolvedValueOnce({ ok: true, status: 200, json: async () => ({ id: 1, username: 'operator', email: 'updated@example.com', full_name: 'Nguyễn Văn A', student_id: 'B23DCCN193' }) })
  vi.stubGlobal('fetch', fetch)
  auth.session.value = { username: 'operator', email: 'operator@example.com', full_name: '', student_id: null, access: 'old-access', refresh: 'refresh-token' }
  await auth.updateProfile({ full_name: 'Nguyễn Văn A', student_id: 'B23DCCN193', email: 'updated@example.com' })
  expect(fetch.mock.calls[0][0]).toBe('http://localhost:8000/api/auth/me/')
  expect(fetch.mock.calls[0][1].method).toBe('PATCH')
  expect(fetch.mock.calls[1][0]).toBe('http://localhost:8000/api/auth/token/refresh/')
  expect(fetch.mock.calls[2][1].headers.Authorization).toBe('Bearer new-access')
  expect(fetch.mock.calls[2][1].body).toBe(fetch.mock.calls[0][1].body)
  expect(auth.session.value).toMatchObject({ full_name: 'Nguyễn Văn A', student_id: 'B23DCCN193', email: 'updated@example.com', access: 'new-access' })
})
it('loads all device pages and exposes backend errors', async () => {
  const fetch = vi.fn().mockResolvedValueOnce({ ok: true, json: async () => ({ results: [{ id: 1 }], next: '/api/v1/devices/?page=2' }) })
    .mockResolvedValueOnce({ ok: true, json: async () => ({ results: [{ id: 2 }], next: null }) })
    .mockResolvedValueOnce({ ok: false, status: 400, json: async () => ({ error: { code: 'INVALID_DATE_RANGE', message: 'Invalid dates.', details: {} } }) })
  vi.stubGlobal('fetch', fetch)
  auth.session.value = { username: 'operator', email: '', full_name: '', student_id: null, access: 'access-token', refresh: 'refresh-token' }
  const api = createHttpApi('http://localhost:8000/api/v1')
  expect(await api.devices()).toEqual([{ id: 1 }, { id: 2 }])
  expect(fetch.mock.calls[1][0]).toContain('limit=100&offset=100')
  await expect(api.sensorTrends()).rejects.toMatchObject({ code: 'INVALID_DATE_RANGE', status: 400 })
})
it('serializes an exact measured value including zero', async () => {
  const fetch = vi.fn().mockResolvedValue({ ok: true, json: async () => ({ count: 0, next: null, previous: null, results: [] }) })
  vi.stubGlobal('fetch', fetch)
  auth.session.value = { username: 'operator', email: '', full_name: '', student_id: null, access: 'access-token', refresh: 'refresh-token' }
  await createHttpApi('http://localhost:8000/api/v1').sensorData({ type: 'TEMPERATURE', value: 0, page: 1, page_size: 10 })
  expect(fetch.mock.calls[0][0]).toBe('http://localhost:8000/api/v1/sensor-data/?type=TEMPERATURE&value=0&limit=10&offset=0')
})
it('blocks data reads when there is no JWT session', async () => {
  const fetch = vi.fn()
  vi.stubGlobal('fetch', fetch)
  await expect(createHttpApi('http://localhost:8000/api/v1').sensorLatest()).rejects.toMatchObject({ code: 'AUTHENTICATION_REQUIRED', status: 401 })
  expect(fetch).not.toHaveBeenCalled()
})
